import { formatAppDate } from '../../utils/date';
import { CAMPUS_TIME_ZONE, campusDateKey } from '../../modules/events/utils/activity-compliance.utils';
import { campusActivitySummary, STATUS_LABELS } from './campus-activity-report';
import type { CampusActivityRow, CampusReportFilters } from './campus-activity-report';
import type { SemesterDocument } from '../../modules/academic/types/academic.types';

export interface CampusReportSnapshot {
  title: string;
  generatedAt: string;
  generatedBy: string;
  date: string;
  filters: string[];
  summary: ReturnType<typeof campusActivitySummary>;
  columns: string[];
  rows: string[][];
}
export function activityDateLabel(row: CampusActivityRow): string {
  if (!row.dates.length) return 'Not scheduled';
  return row.dates.map((date) => formatAppDate(date)).join(', ');
}
export function activityDeadlineLabel(row: CampusActivityRow): string {
  if (row.exempt) return 'FL exempt';
  if (!row.deadline) return 'Not available';
  const remaining = row.missingFL && row.daysRemaining !== null
    ? row.daysRemaining < 0 ? ` (${Math.abs(row.daysRemaining)} days overdue)` : ` (${row.daysRemaining} days remaining)` : '';
  return `${formatAppDate(row.deadline)}${remaining}`;
}
export function campusReportSnapshot(rows: CampusActivityRow[], filters: CampusReportFilters, periods: SemesterDocument[], organizations: any[], generatedBy: string, now = new Date()): CampusReportSnapshot {
  const quickLabels: Record<string, string> = { ALL: 'All', missing_par: 'Missing PAR', missing_fl: 'Missing FL', returned: 'Returned', my_signature: 'Awaiting my signature', cleared: 'Fully cleared', needs_action: 'Needs action', overdue: 'Overdue FL' };
  const status = (value: string) => value === 'ALL' ? 'All' : STATUS_LABELS[value] || value;
  const period = filters.period === 'ACTIVE' ? `Active periods: ${periods.filter((item) => item.status === 'ACTIVE' && !item.archived).map((item) => item.label || `${item.academicYear} ${item.semester}`).join(', ') || 'None configured'}`
    : filters.period === 'ALL' ? 'All periods' : periods.find((item) => item.id === filters.period)?.label || filters.period;
  return {
    title: 'Campus Activity Status & Compliance Report',
    generatedAt: new Intl.DateTimeFormat('en-PH', { timeZone: CAMPUS_TIME_ZONE, dateStyle: 'medium', timeStyle: 'short' }).format(now) + ' (Philippine time)',
    generatedBy: generatedBy || 'Institutional Signatory', date: campusDateKey(now),
    filters: [
      `Academic period: ${period}`, `Academic year: ${filters.academicYear}`, `Term: ${filters.semester}`,
      `Scope: ${filters.scope}`, `Organizer: ${filters.organizationId === 'ALL' ? 'All' : filters.organizationId === 'sas' ? 'Student Affairs & Services (SAS)' : organizations.find((org) => org.id === filters.organizationId)?.name || filters.organizationId}`,
      `Activity dates: ${filters.startDate || 'Any'} to ${filters.endDate || 'Any'}`,
      `Proposal: ${status(filters.proposalStatus)}`, `Activity status: ${status(filters.activityState)}`,
      `FL: ${status(filters.flStatus)}`, `PAR: ${status(filters.parStatus)}`, `Quick filter: ${quickLabels[filters.quick] || filters.quick}`,
      `Search: ${filters.search || 'None'}`,
    ],
    summary: campusActivitySummary(rows),
    columns: ['Activity name / reference', 'Organizer', 'Activity dates', 'Proposal', 'Activity status', 'Financial liquidation', 'Post-activity report', 'Outstanding requirements', 'FL submission deadline'],
    rows: rows.map((row) => [
      `${row.title}\n${row.reference}`, row.organizer, activityDateLabel(row), STATUS_LABELS[row.proposalStatus] || row.proposalStatus,
      STATUS_LABELS[row.activityState], STATUS_LABELS[row.flStatus], STATUS_LABELS[row.parStatus], row.outstanding, activityDeadlineLabel(row),
    ]),
  };
}
function csvCell(value: unknown): string {
  let text = String(value ?? '');
  if (/^[\s]*[=+\-@\t\r]/.test(text)) text = `'${text}`;
  return `"${text.replace(/"/g, '""')}"`;
}
export function campusReportCSV(snapshot: CampusReportSnapshot): string {
  const records = [
    [snapshot.title], ['Generated at', snapshot.generatedAt], ['Generated by', snapshot.generatedBy],
    ...snapshot.filters.map((filter) => [filter]),
    ['Activities', snapshot.summary.total, 'Concluded', snapshot.summary.concluded, 'PAR not submitted', snapshot.summary.missingPAR, 'FL not submitted', snapshot.summary.missingFL, 'Returned', snapshot.summary.returned, 'Fully cleared', snapshot.summary.cleared],
    [], snapshot.columns, ...snapshot.rows,
  ];
  return '\uFEFF' + records.map((record) => record.map(csvCell).join(',')).join('\r\n');
}
export function downloadCampusCSV(snapshot: CampusReportSnapshot) {
  const url = URL.createObjectURL(new Blob([campusReportCSV(snapshot)], { type: 'text/csv;charset=utf-8;' }));
  const link = document.createElement('a');
  link.href = url;
  link.download = `Campus_Activity_Compliance_${snapshot.date}.csv`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
}

/** Full, wrapped, paginated table. Export every filtered row, including long cells. */
export async function createCampusReportPDF(snapshot: CampusReportSnapshot) {
  const { jsPDF } = await import('jspdf');
  const pdf = new jsPDF({ orientation: 'landscape', unit: 'mm', format: 'a3' });
  const margin = 15;
  const widths = [58, 32, 30, 24, 28, 32, 29, 65, 32];
  const height = pdf.internal.pageSize.getHeight();
  const bottom = height - 16;
  const plain = (value: string) => value.replace(/[—–]/g, '-').replace(/₱/g, 'PHP ').replace(/·/g, '|');
  const writeLines = (value: string, size = 8) => {
    pdf.setFontSize(size);
    const lines = pdf.splitTextToSize(plain(value), 390) as string[];
    for (const line of lines) {
      if (y + 4 > bottom) { pdf.addPage(); y = margin; }
      pdf.text(line, margin, y);
      y += 4;
    }
  };
  let y = margin;
  pdf.setFont('helvetica', 'bold');
  writeLines('STI College Ormoc', 12);
  y += 2;
  writeLines(snapshot.title, 15);
  y += 2;
  pdf.setFont('helvetica', 'normal');
  writeLines(`Generated: ${snapshot.generatedAt} | By: ${snapshot.generatedBy}`);
  snapshot.filters.forEach((filter) => writeLines(filter));
  y += 2;
  writeLines(`Activities: ${snapshot.summary.total} | Concluded: ${snapshot.summary.concluded} | PAR not submitted: ${snapshot.summary.missingPAR} | FL not submitted: ${snapshot.summary.missingFL} | Returned: ${snapshot.summary.returned} | Fully cleared: ${snapshot.summary.cleared}`);
  y += 3;
  const drawHeader = () => {
    if (y + 14 > bottom) { pdf.addPage(); y = margin; }
    pdf.setFont('helvetica', 'bold'); pdf.setFontSize(8); pdf.setFillColor(0, 26, 77); pdf.setTextColor(255);
    let x = margin;
    snapshot.columns.forEach((column, index) => {
      pdf.rect(x, y, widths[index], 12, 'F');
      pdf.text(pdf.splitTextToSize(plain(column), widths[index] - 4), x + 2, y + 4);
      x += widths[index];
    });
    y += 12;
    pdf.setTextColor(30); pdf.setFont('helvetica', 'normal'); pdf.setFontSize(8);
  };
  drawHeader();
  snapshot.rows.forEach((row, rowIndex) => {
    const cells = row.map((value, index) => pdf.splitTextToSize(plain(value), widths[index] - 4) as string[]);
    let remaining = Math.max(...cells.map((cell) => cell.length));
    let offset = 0;
    while (remaining > 0) {
      if (y + 8 > bottom) { pdf.addPage(); y = margin; drawHeader(); }
      const count = Math.min(remaining, Math.floor((bottom - y - 4) / 4));
      const rowHeight = count * 4 + 4;
      let x = margin;
      cells.forEach((cell, index) => {
        pdf.setFillColor(rowIndex % 2 ? 245 : 255); pdf.setDrawColor(220);
        pdf.rect(x, y, widths[index], rowHeight, 'FD');
        const lines = cell.slice(offset, offset + count);
        if (lines.length) pdf.text(lines, x + 2, y + 5);
        x += widths[index];
      });
      y += rowHeight; remaining -= count; offset += count;
    }
  });
  const pages = pdf.getNumberOfPages();
  for (let page = 1; page <= pages; page++) {
    pdf.setPage(page); pdf.setFontSize(8); pdf.setTextColor(100);
    pdf.text(`STI Sync | Generated ${snapshot.generatedAt} | Page ${page} of ${pages}`, margin, height - 7);
  }
  return pdf;
}
export async function downloadCampusPDF(snapshot: CampusReportSnapshot) {
  const pdf = await createCampusReportPDF(snapshot);
  pdf.save(`Campus_Activity_Compliance_${snapshot.date}.pdf`);
}
